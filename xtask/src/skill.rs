//! The agent skill (architecture §9): `reference.md` generated from the
//! CLI's own definitions, and the checks that keep the hand-written files
//! honest.

use clap::CommandFactory;
use junc_cli::args::Cli;
use junc_cli::errors::CODES;
use std::fmt::Write;
use std::path::{Path, PathBuf};

pub fn dir(root: &Path) -> PathBuf {
    root.join("skill/junc")
}

fn help_of(cmd: &mut clap::Command, path: &str, out: &mut String) {
    let help = cmd.render_help().to_string();
    let _ = writeln!(out, "### `{path}`\n\n```text\n{}\n```\n", help.trim_end());
    let mut subs: Vec<clap::Command> = cmd.get_subcommands().cloned().collect();
    for sub in &mut subs {
        if sub.get_name() == "help" {
            continue;
        }
        let name = format!("{path} {}", sub.get_name());
        help_of(sub, &name, out);
    }
}

/// The generated `reference.md`.
pub fn reference() -> String {
    let mut out = String::from(
        "# Reference\n\n\
         Generated by `cargo xtask skill-ref` from the `junc` command definitions\n\
         and its error table; do not edit by hand.\n\n\
         ## JSON output\n\n\
         With `--json`, every command prints one document:\n\n\
         ```json\n\
         {\"junc\": 1, \"ok\": true, \"revision\": 42, \"data\": {}}\n\
         {\"junc\": 1, \"ok\": false, \"error\": {\"code\": \"E_CONFIG_RANGE\", \"message\": \"volume is 900\",\n \
         \"hint\": \"Volume is a percentage from 0 to 150.\", \"location\": {\"file\": \"…\", \"line\": 7, \"column\": 10}}}\n\
         ```\n\n\
         `revision` is the config revision after the command (pass it to\n\
         `--expect-revision`). `junc describe --json` → `data`: `state`, `revision`,\n\
         `config_file`, `config_error[]`, `junctions[]`, `capture_apps[]`, `defaults`,\n\
         `candidates[]`. `junc apply FILE --dry-run --json` → `data.plan`: `summary[]`,\n\
         `actions[]`, `complete`, `deferred[]`, `junctions[]`.\n\n\
         ## Error codes and exit codes\n\n\
         | Code | Exit | Meaning and what to do |\n| --- | --- | --- |\n",
    );
    for c in CODES {
        let _ = writeln!(out, "| `{}` | {} | {} |", c.code, c.exit, c.meaning);
    }
    out.push_str("\nExit 0 means success.\n\n## Commands\n\n");
    let mut cmd = Cli::command();
    // Built, so subcommands show their full usage (`junc input add …`).
    cmd.build();
    help_of(&mut cmd, "junc", &mut out);
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// Words of one shell line, honouring quotes; `None` for lines that are
/// not a plain `junc …` call (pipes, substitutions, other programs).
fn junc_words(line: &str) -> Option<Vec<String>> {
    let line = line.trim();
    if !line.starts_with("junc ") || line.contains("$(") || line.contains('|') {
        return None;
    }
    let mut words = Vec::new();
    let (mut cur, mut quote, mut any) = (String::new(), None, false);
    for c in line.chars() {
        match (quote, c) {
            (None, '#') if cur.is_empty() => break,
            (None, '"' | '\'') => {
                quote = Some(c);
                any = true;
            }
            (Some(q), c) if c == q => quote = None,
            (None, c) if c.is_whitespace() => {
                if any || !cur.is_empty() {
                    words.push(std::mem::take(&mut cur));
                    any = false;
                }
            }
            (_, c) => cur.push(c),
        }
    }
    if any || !cur.is_empty() {
        words.push(cur);
    }
    Some(words)
}

/// Fenced code blocks: (language, first line number, body).
fn blocks(text: &str) -> Vec<(String, usize, String)> {
    let mut out = Vec::new();
    let mut open: Option<(String, usize, String)> = None;
    for (n, line) in text.lines().enumerate() {
        if let Some(rest) = line.trim_start().strip_prefix("```") {
            match open.take() {
                Some(b) => out.push(b),
                None => open = Some((rest.trim().to_owned(), n + 2, String::new())),
            }
        } else if let Some((_, _, body)) = open.as_mut() {
            body.push_str(line);
            body.push('\n');
        }
    }
    out
}

/// All problems found in the skill; empty when it is fine.
pub fn check(root: &Path) -> Vec<String> {
    let dir = dir(root);
    let mut problems = Vec::new();
    let skill = std::fs::read_to_string(dir.join("SKILL.md")).unwrap_or_default();
    let front = skill
        .strip_prefix("---\n")
        .and_then(|r| r.split_once("\n---\n"))
        .map(|(f, _)| f);
    match front {
        None => problems.push("SKILL.md: no frontmatter".to_owned()),
        Some(f) => {
            if !f.lines().any(|l| l.trim() == "name: junc") {
                problems.push("SKILL.md: frontmatter needs `name: junc`".to_owned());
            }
            if !f
                .lines()
                .any(|l| l.starts_with("description: ") && l.len() > 60)
            {
                problems.push("SKILL.md: frontmatter needs a description with triggers".to_owned());
            }
        }
    }
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .map(|d| d.flatten().map(|e| e.path()).collect())
        .unwrap_or_default();
    files.retain(|p| p.extension().is_some_and(|e| e == "md"));
    files.sort();
    for file in &files {
        let name = file
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        if name == "reference.md" {
            continue;
        }
        let text = std::fs::read_to_string(file).unwrap_or_default();
        // Every file the skill points at exists.
        for word in text.split(|c: char| c.is_whitespace() || c == '(' || c == ')' || c == ',') {
            let w = word.trim_matches(|c: char| c == '.' || c == ':' || c == '`' || c == '*');
            if w.ends_with(".md") && !w.contains('/') && !dir.join(w).exists() {
                problems.push(format!("{name}: refers to missing {w}"));
            }
        }
        for (lang, line, body) in blocks(&text) {
            match lang.as_str() {
                "sh" | "bash" => {
                    for (k, l) in body.lines().enumerate() {
                        if let Some(words) = junc_words(l)
                            && let Err(e) = <Cli as clap::Parser>::try_parse_from(&words)
                        {
                            let first = e.to_string().lines().next().unwrap_or_default().to_owned();
                            problems.push(format!("{name}:{}: `{}`: {first}", line + k, l.trim()));
                        }
                    }
                }
                "toml" => {
                    if let Err(d) = junc_core::config::load(&body, &format!("{name}:{line}")) {
                        for x in d {
                            problems.push(format!("{name}:{line}: config example: {x}"));
                        }
                    }
                }
                _ => {}
            }
        }
    }
    let current = std::fs::read_to_string(dir.join("reference.md")).unwrap_or_default();
    if current != reference() {
        problems.push("reference.md is stale: run `cargo xtask skill-ref`".to_owned());
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shell_lines_split_like_a_shell() {
        assert_eq!(
            junc_words(r#"junc create junction "Zoom Mic"   # comment"#),
            Some(vec![
                "junc".into(),
                "create".into(),
                "junction".into(),
                "Zoom Mic".into()
            ])
        );
        assert_eq!(junc_words("cp \"$(junc config path)\" /tmp/x"), None);
        assert_eq!(junc_words("junc describe --json | jq ."), None);
    }

    /// The skill in the repository passes its own checks.
    #[test]
    fn the_skill_passes_skill_check() {
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..");
        let problems = check(&root);
        assert!(problems.is_empty(), "{}", problems.join("\n"));
    }

    /// A broken command or config example is caught.
    #[test]
    fn mistakes_are_caught() {
        let root = std::env::temp_dir().join(format!("junc-skill-check-{}", std::process::id()));
        let dir = dir(&root);
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&dir).expect("dir");
        std::fs::write(
            dir.join("SKILL.md"),
            "---\nname: junc\ndescription: short\n---\nSee nope.md.\n```sh\njunc frobnicate\njunc volume zoom 80\n```\n```toml\nschema = 1\nvolme = 3\n```\n",
        )
        .expect("write");
        let p = check(&root);
        let joined = p.join("\n");
        for want in [
            "description with triggers",
            "missing nope.md",
            "junc frobnicate",
            "unknown key",
            "reference.md is stale",
        ] {
            assert!(joined.contains(want), "missing {want:?} in:\n{joined}");
        }
        assert!(!joined.contains("junc volume zoom 80"), "{joined}");
        let _ = std::fs::remove_dir_all(&root);
    }
}
